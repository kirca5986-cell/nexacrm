function buildSeedReport(
  id: string,
  number: string,
  job: FieldJob,
  machine: typeof MACHINES[number],
  wll: number,
  designPressure: number | null,
  approvedAt: number
): Report {
  const tpl = getInspectionTemplate(machine);
  const inspectionDate = new Date(approvedAt).toISOString().slice(0, 10);
  const nextDate = new Date(approvedAt + tpl.nextInspectionMonths * 30 * day)
    .toISOString()
    .slice(0, 10);

  return {
    id,
    number,
    jobId: job.id,
    workOrderNumber: job.workOrderNumber,
    customerId: job.customerId,
    customerName: job.customerName,
    machineTypeId: machine.id,
    machineTypeName: machine.name,
    kkCode: machine.kkCode,
    krCode: machine.krCode,
    reportTitle: machine.reportTitle,
    serialNo: job.serialNo,
    chassisNo: machine.category === 'kendinden-tahrikli' ? job.serialNo : '-',
    isgKatipContractId: 'IK-992812',
    ekipnetRegNo: ENGINEER.ekipnetNo,
    engineerName: job.assignedEngineer,
    engineerRegNo: job.engineerRegNo,
    inspectionDate,
    nextInspectionDate: nextDate,
    wll,
    designPressure,
    inspectionItems: buildInspectionItems(tpl),
    loadTests: buildLoadTests(tpl, wll),
    wallThickness: tpl.wallThicknessCheck ? buildWallThicknessDefaults() : [],
    safetyValveSetPressure: tpl.safetyValveCheck && designPressure ? +designPressure.toFixed(2) : null,
    manometerCalibrated: tpl.manometerCheck,
    finalResult: 'UYGUN',
    status: 'Onaylandı',
    createdAt: approvedAt,
    approvedAt,
  };
}
